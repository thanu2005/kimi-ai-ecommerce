async def seed() -> None:
    """Create tables (if absent) and insert all seed rows.

    Idempotent: rows that already exist with the same PK are skipped via
    ``merge`` so the seeder can be re-run safely during development.
    """
    await create_db_and_tables()

    all_objects = [
        *_products(),  *_products2(),
        *_campaigns(), *_campaigns2(),
        *_orders(),    *_orders2(),
        *_tickets(),   *_tickets2(),
    ]

    async with get_session() as session:
        for obj in all_objects:
            await session.merge(obj)

    print(
        "Seed complete - "
        "15 products, 11 campaigns, 45 order lines, 10 support tickets inserted."
    )


if __name__ == "__main__":
    asyncio.run(seed())

