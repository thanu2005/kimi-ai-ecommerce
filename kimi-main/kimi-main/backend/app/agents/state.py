"""LangGraph state definitions for the multi-agent orchestration system.

Two-tier state design
---------------------
- ``OrchestratorState`` — shared blackboard for the top-level supervisor
  graph.  Every domain subgraph reads from and writes to this structure via
  explicit input/output field mappings.

- ``SubAgentState`` — isolated per-subgraph state.  The supervisor maps the
  relevant slice of the parent state into this structure before invoking a
  subgraph, and maps discoveries back out when it returns.

Whiteboard contract
-------------------
``whiteboard`` is the cross-agent shared scratchpad.  Each domain agent writes
structured discovery entries under its own namespaced key, e.g.::

    state["whiteboard"]["inventory"] = {"flags": [...], "summary": "..."}
    state["whiteboard"]["sales"]     = {"flags": [...], "summary": "..."}

The synthesizer node reads the entire whiteboard to compile the final report.
"""

import operator
from typing import Annotated, Any, Dict, List

from typing_extensions import TypedDict


class OrchestratorState(TypedDict):
    """Top-level shared state for the master supervisor graph.

    Fields
    ------
    query : str
        The original high-level question or instruction from the operator /
        API caller (e.g., "Run a full health check for today").
    session_id : str
        Unique session tracking ID — maps to the LangGraph ``thread_id`` used
        by ``AsyncPostgresSaver`` for checkpoint persistence.
    intent : str
        Parsed intent label set by the supervisor router node.
        Examples: ``"diagnostic"``, ``"remediation"``, ``"monitoring"``.
    selected_agents : List[str]
        Router-selected domain agent names for this run.
        Subset of: ``["inventory", "sales", "marketing", "support"]``.
    whiteboard : Dict[str, Any]
        Collaborative short-term shared scratchpad.  Sub-agents write their
        domain observations under namespaced keys during the parallel scan
        phase.  The reflection node reads the full dict for cross-domain
        correlation analysis.
    orchestrator_goals : str
        Directives set by the orchestrator to guide sub-agents during a
        rethink / re-scan loop.  Empty string on first pass.
    agent_goals : Dict[str, str]
        Per-domain focused directives auto-generated by the orchestrator LLM
        during Phase 1 intent extraction.  Each value is a one-sentence goal
        telling that domain's agent what to specifically investigate, e.g.::

            {"inventory": "Identify stockout risk for products with high sales velocity",
             "support":   "Quantify fulfillment-delay complaints from the last 6 hours"}

        Never set by the API caller — generated internally and stored in state
        so ``collaborative_retrospection_node`` can pass them to agents again.
    memory_context : str
        RAG context injected from Qdrant's ``support_ticket_embeddings``
        collection — historical incident summaries relevant to the current
        query.  Populated by the memory retrieval node before agent dispatch.
    incident_memory_context : Dict[str, Any]
        Structured cross-thread incident matches from Qdrant similarity search.
        Includes ranked incident hits and similarity scores.
    action_effectiveness_context : str
        Compact historical effectiveness summary for previously executed actions.
        Injected into sub-agents so remediation proposals can cite precedents.
    messages : list
        Raw LLM conversation history across all iterations.  Uses
        ``operator.add`` reducer so new messages are appended rather than
        overwritten on each node transition.
    proposed_actions : List[Dict[str, Any]]
        Structured JSON action proposals generated by domain agents for
        display in the operator UI.  Each entry has keys:
        ``agent``, ``tool``, ``params``, ``rationale``, ``priority``.
    pending_execution : List[Dict[str, Any]]
        Approved actions from previous HITL iterations that are staged and
        waiting for all rejections to be resolved before final execution.
        Grows across iterations; executed together with the final approved
        set in a single atomic pass.
    rejected_actions : List[Dict[str, Any]]
        Actions the human rejected at the current HITL interrupt.  Each
        entry carries the original action dict plus a ``rejection_reason``
        string.  Consumed by ``orchestrator_refinement_node`` to generate
        refined goals for the affected domains, then cleared.
    human_note : str
        Optional freeform text the operator adds when rejecting actions.
        Injected into the orchestrator refinement prompt as additional
        context.  Empty string when not provided.
    iteration : int
        HITL feedback loop counter.  Starts at 1 on the first run.
        Incremented by ``orchestrator_refinement_node`` on each rejection
        loop.  Used to skip Phase 1.5 on feedback iterations.
    retry_domains : List[str]
        Domains that need to re-run Phase 1 due to rejected actions.
        Set by ``orchestrator_refinement_node``; read by
        ``parallel_domain_scan_node`` to skip intent extraction and run
        only the affected agents.  Cleared after Phase 1 completes.
    """
    query: str
    session_id: str
    intent: str
    selected_agents: List[str]
    whiteboard: Dict[str, Any]
    orchestrator_goals: str
    agent_goals: Dict[str, str]
    memory_context: str
    incident_memory_context: Dict[str, Any]
    action_effectiveness_context: str
    messages: Annotated[list, operator.add]
    proposed_actions: List[Dict[str, Any]]
    pending_execution: List[Dict[str, Any]]
    rejected_actions: List[Dict[str, Any]]
    human_note: str
    iteration: int
    retry_domains: List[str]
    formatted_response: str
    off_topic: bool
    query_type: str
    requires_remediation: bool
    needs_incident_memory: bool
    needs_action_effectiveness: bool
    hitl_human_reviewed: bool


class SubAgentState(TypedDict):
    """Isolated state for each domain subgraph.

    The supervisor maps a slice of ``OrchestratorState`` into this structure
    before invoking the subgraph, and extracts ``discoveries`` and
    ``proposed_actions`` back out into the parent state on return.

    Fields
    ------
    messages : list
        Subgraph-local message history for the domain agent's ReAct loop.
        Initialised from the parent's messages but not written back — keeps
        subgraph reasoning isolated from the shared conversation thread.
    query : str
        Passed through from parent state so the agent knows the original ask.
    memory_context : str
        Historical RAG context passed in from the parent for reference.
    incident_memory_context : Dict[str, Any]
        Structured cross-thread incident retrieval payload for precedent checks.
    action_effectiveness_context : str
        Historical action effectiveness summary for proposal ranking.
    discoveries : List[str]
        String log of findings accumulated by this agent during its analysis
        loop.  Written into ``whiteboard[<domain>]["findings"]`` by the
        supervisor's merge node.
    agent_goal : str
        Domain-specific directive passed in from ``OrchestratorState["agent_goals"][domain]``.
        Gives the agent focused intent beyond the raw query.  Empty string
        when no per-domain goal is set.
    proposed_actions : List[Dict[str, Any]]
        Domain-specific action proposals to be merged into the parent's
        ``proposed_actions`` list.
    query_type : str
        Forwarded from ``OrchestratorState`` so each agent's ReAct loop
        and output-format suffix know whether to emit proposed_actions.
        One of ``"REPORT"``, ``"DIAGNOSTIC"``, ``"ACTION"``.
    """
    messages: Annotated[list, operator.add]
    query: str
    memory_context: str
    incident_memory_context: Dict[str, Any]
    action_effectiveness_context: str
    agent_goal: str
    discoveries: List[str]
    proposed_actions: List[Dict[str, Any]]
    query_type: str

